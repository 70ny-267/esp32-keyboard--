def get_key_distance(char1: str, char2: str) -> float:
    """计算两键在键盘上的欧几里得物理距离"""
    c1 = char1.lower()
    c2 = char2.lower()
    if c1 in SHIFT_SYMBOLS:
        c1 = SHIFT_SYMBOLS[c1]
    if c2 in SHIFT_SYMBOLS:
        c2 = SHIFT_SYMBOLS[c2]
        
    pos1 = KEY_COORDS.get(c1, (2, 5.0))
    pos2 = KEY_COORDS.get(c2, (2, 5.0))
    return ((pos1[0] - pos2[0])**2 + (pos1[1] - pos2[1])**2) ** 0.5
